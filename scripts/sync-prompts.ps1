<#
.SYNOPSIS
  Sync Nova Canvas shared prompts across OpenCode / Continue / GitHub ends.
.DESCRIPTION
  Canonical sources (edit these by hand):
    AGENTS.md                          repo conventions (GitHub end; OpenCode auto-reads it)
    canvas-agent/agent-instructions.md canvas-agent runtime behavior
  Generated, do-NOT-edit artifacts (regenerated by this script):
    .continue/rules/nova-canvas-conventions.mdc   Continue end (conventions + agent instructions)
    .agents/skills/nova-canvas-agent/SKILL.md       OpenCode end (agent instructions as a skill)
  Usage:
    pwsh scripts/sync-prompts.ps1          write the derived ends
    pwsh scripts/sync-prompts.ps1 --check  verify in sync, exit 1 on drift (for CI)
#>
param([switch]$Check)
$ErrorActionPreference = 'Stop'

$repoRoot  = Resolve-Path (Join-Path $PSScriptRoot '..')
$agentsPath = Join-Path $repoRoot 'AGENTS.md'
$agentPath  = Join-Path $repoRoot 'canvas-agent/agent-instructions.md'

function Read-Utf8($p) { return (Get-Content -Raw -Encoding UTF8 $p) }
$agents = Read-Utf8 $agentsPath
$agent  = Read-Utf8 $agentPath

$autoGen = '<!-- AUTO-GENERATED by scripts/sync-prompts — do not edit. Edit AGENTS.md / canvas-agent/agent-instructions.md and re-run. -->'

$mdcBody = "$autoGen`n`n# Nova Canvas (启画) — 共享提示（同步源）`n`n以下由 AGENTS.md 与 canvas-agent/agent-instructions.md 合并生成，请勿手改。`n`n--- AGENTS.md ---`n`n$agents`n`n--- canvas-agent/agent-instructions.md ---`n`n$agent"
$mdc = "---`nname: nova-canvas-conventions`ndescription: Nova Canvas (启画) shared conventions + canvas-agent instructions, synced from AGENTS.md and canvas-agent/agent-instructions.md.`nalwaysApply: true`n---`n`n$mdcBody"

$skillBody = "$autoGen`n`n$agent"
$skill = "---`nname: nova-canvas-agent`ndescription: Runtime instructions for operating the Nova Canvas agent via canvas MCP tools (canvas_get_state, canvas_apply_ops, workbench_image_*, etc.).`n---`n`n$skillBody"

function Normalize($s) { return ($s -replace "`r`n", "`n").TrimEnd("`n") + "`n" }
$mdcN   = Normalize $mdc
$skillN = Normalize $skill

$mdcPath   = Join-Path $repoRoot '.continue/rules/nova-canvas-conventions.mdc'
$skillPath = Join-Path $repoRoot '.agents/skills/nova-canvas-agent/SKILL.md'

function Ensure-Parent($p) { $d = Split-Path $p; if (!(Test-Path $d)) { New-Item -ItemType Directory -Force -Path $d | Out-Null } }
function Write-Utf8($p, $c) { Ensure-Parent $p; [System.IO.File]::WriteAllText($p, $c, (New-Object System.Text.UTF8Encoding $false)) }

if ($Check) {
    $drift = @()
    if (!(Test-Path $mdcPath) -or (Normalize (Read-Utf8 $mdcPath)) -ne $mdcN) { $drift += $mdcPath }
    if (!(Test-Path $skillPath) -or (Normalize (Read-Utf8 $skillPath)) -ne $skillN) { $drift += $skillPath }
    if ($drift.Count -gt 0) {
        Write-Host "DRIFT detected (regenerate with scripts/sync-prompts):"
        $drift | ForEach-Object { Write-Host "  $_" }
        exit 1
    }
    Write-Host "OK: all prompt ends in sync."
    exit 0
}
else {
    Write-Utf8 $mdcPath $mdcN
    Write-Utf8 $skillPath $skillN
    Write-Host "Wrote:`n  $mdcPath`n  $skillPath"
    exit 0
}
