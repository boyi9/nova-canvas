# file: backend/pro/generators/ae_script_builder.py
# 作用：把 Nova 的包装方案编译为可被 AE 执行的 ExtendScript(.jsx)，
#      并生成 aerender 无头渲染命令。图层命名严格遵循"命名即契约"。
# 依赖：仅 Python 标准库
from typing import List, Dict
import json

# 图层命名契约（Nexrender 等按 layerName 替换素材，必须区分大小写一致）
LAYER_PREFIX = {
    "title": "TITLE", "logo": "LOGO", "card_data": "CARD_DATA",
    "card_knowledge": "CARD_KNOWLEDGE", "product": "PRODUCT",
    "subtitle": "SUBTITLE", "badge": "BADGE", "cta": "CTA",
}


def _esc(s: str) -> str:
    """转义进入 JSX 字符串字面量的内容，避免引号/反斜杠破坏脚本。"""
    return s.replace("\\", "\\\\").replace('"', '\\"')


def build_ae_script(comp_name: str, width: int, height: int, fps: int,
                    duration_sec: float, layers: List[Dict]) -> str:
    """layers: [{'role':'title','text':'...','in':0.5,'out':3.0}, ...]"""
    lines = [
        "// Auto-generated by Nova Canvas — DO NOT EDIT MANUALLY",
        "app.beginUndoGroup(\"Nova Build\");",
        f"var comp = app.project.items.addComp(\"{_esc(comp_name)}\", "
        f"{width}, {height}, 1, {duration_sec}, {fps});",
    ]
    counters: Dict[str, int] = {}
    for lyr in layers:
        role = lyr["role"]
        if role not in LAYER_PREFIX:
            raise ValueError(f"未登记的图层角色: {role}")
        counters[role] = counters.get(role, 0) + 1
        name = f"{LAYER_PREFIX[role]}_{counters[role]:02d}"
        lines.append(f"// role={role} -> layer={name}")
        if role in ("title", "subtitle", "card_data", "card_knowledge", "cta"):
            txt = lyr.get("text", "")
            lines.append(
                f'var t = comp.layers.addText("{_esc(txt)}"); t.name = "{name}";'
            )
            lines.append(
                f't.inPoint = {lyr.get("in", 0.0)}; t.outPoint = {lyr.get("out", duration_sec)};'
            )
        else:
            lines.append(
                f'var s = comp.layers.addSolid([1,1,1], "{name}", '
                f'{width}, {height}, 1); s.name = "{name}";'
            )
            lines.append(
                f's.inPoint = {lyr.get("in", 0.0)}; s.outPoint = {lyr.get("out", duration_sec)};'
            )
    lines.append("app.endUndoGroup();")
    return "\n".join(lines)


def build_aerender_cmd(aep_path: str, comp_name: str, out_path: str,
                       start: int = 0, end: int = -1) -> str:
    """构造 aerender 无头渲染命令（AE 官方 CLI）。end=-1 表示渲染整个合成。"""
    return (f'aerender -project "{aep_path}" -comp "{comp_name}" '
            f'-s {start} -e {end} -output "{out_path}"')


